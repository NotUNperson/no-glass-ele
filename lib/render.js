'use strict';
/**
 * render.js —— 由 profile + 探测结果渲染启动脚本与 per-app 文档
 *
 * 两条硬约束：
 *
 * 1. **生成的 .cmd 必须是纯 ASCII + CRLF。**
 *    中文版 Windows 的 cmd 默认按 GBK(936) 解析。若 .cmd 存成 UTF-8 且含中文，
 *    字节被错读后会产生 `&`、`|` 之类的分隔符，把 `rem` 注释行撕成一条条
 *    "命令"，报出 `'xxx' 不是内部或外部命令` 这种莫名其妙的错误。
 *    所以：.cmd 里一个非 ASCII 字符都不能有，中文说明一律放 README。
 *    换行统一 CRLF —— 见 .gitattributes（core.autocrlf 未设置时必须显式锁死）。
 *
 * 2. **不臆造未知信息。**
 *    静态探测测不出的东西（运行时端口占用、页面上到底有没有玻璃），
 *    一律标注为"需人工确认"，不假装知道。
 */

const path = require('path');
const crypto = require('crypto');

const CRLF = '\r\n';

/**
 * 生成产物的内容指纹。
 *
 * 为什么不用文件 mtime 判断"产物是否过期"：mtime 在 git 操作后完全不可靠 ——
 * 一次 clone / checkout 会把所有文件的时间戳刷成同一刻，谁新谁旧分不出来。
 * 所以把 profile 的内容算成指纹写进产物，doctor 比对指纹即可。
 */
function fingerprint(profile, extra = '') {
  const payload = JSON.stringify({
    // 只取会影响产物的字段；detected 里的探测时间不该让产物"过期"
    name: profile.name,
    displayName: profile.displayName,
    exe: profile.exe,
    exeGlob: profile.exeGlob,
    processName: profile.processName,
    styleId: profile.styleId,
    defaultPort: profile.defaultPort,
    reservedPorts: profile.reservedPorts,
    isolateEnv: profile.isolateEnv,
    dataDirEnv: profile.dataDirEnv,
    urlFilter: profile.urlFilter,
    // 下面这组是"会写进产物 README / 影响启动方式"的字段。
    // 曾经漏在这里：改了它们指纹不变 → doctor 认为产物是最新的 →
    // 静默不一致（用户以为配置生效了，实际启动器还是旧的）。
    cssExtra: profile.cssExtra,
    emulateColorScheme: profile.emulateColorScheme,
    darkreader: profile.darkreader,
    darkreaderTheme: profile.darkreaderTheme,
    appArgs: profile.appArgs,
    native: profile.native,
    notes: profile.notes,
    detected: profile.detected
      ? {
          electron: profile.detected.electron,
          fuses: profile.detected.fuses,
          canUseNative: profile.detected.canUseNative,
          windowLayerGlass: profile.detected.windowLayerGlass,
          hasPageGlass: profile.detected.hasPageGlass,
          singleInstance: profile.detected.singleInstance,
          userDataOverride: profile.detected.userDataOverride,
        }
      : null,
  });
  return crypto.createHash('sha256').update(payload + '\0' + extra).digest('hex').slice(0, 12);
}

/** 断言纯 ASCII，越界即抛。防止将来改模板时不小心塞进中文。 */
function assertAscii(text, label) {
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c > 0x7e || (c < 0x20 && c !== 0x0a && c !== 0x0d && c !== 0x09)) {
      throw new Error(
        `${label} 含非 ASCII 字符（位置 ${i}，U+${c.toString(16).toUpperCase()}）。` +
          `.cmd 必须保持纯 ASCII，中文说明请写进 README。`
      );
    }
  }
}

/** 统一换行为 CRLF，并确保以 CRLF 结尾。 */
function toCrlf(text) {
  return text.replace(/\r\n|\r|\n/g, CRLF).replace(/(\r\n)+$/, '') + CRLF;
}

/** 转义 % 以适配 batch（% 在 cmd 里是变量引导符）。 */
function batchEscape(s) {
  return String(s).replace(/%/g, '%%');
}

