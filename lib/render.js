/**
 * 把一个可能含非 ASCII 的名字转成可安全写进 .cmd 的标签。
 *
 * 为什么需要：应用名可能是中文（如 "Todo清单"），但 .cmd 必须纯 ASCII ——
 * 中文版 Windows 的 cmd 按 GBK 解析，UTF-8 中文会被错读成 `&`、`|` 之类的
 * 分隔符，把 rem 注释行撕成一条条"命令"。
 *
 * 名字在 .cmd 里只是注释，纯装饰；中文全名照旧写进 README（UTF-8 不受限）。
 */
function asciiLabel(name, fallback) {
  const s = String(name == null ? '' : name);
  if (s.trim() && /^[\x20-\x7e]+$/.test(s)) return s;
  return fallback || 'app';
}

/** 名字是否含非 ASCII（用于决定要不要在 .cmd 里加一句提示）。 */
function hasNonAscii(s) {
  return /[^\x20-\x7e]/.test(String(s == null ? '' : s));
}

/**
 * 生成一个启动器 .cmd。
 *
 * 结构沿用原 zcode-no-glass 的 start-zcode-noglass.cmd：
 *   @echo off → chcp 65001（UTF-8）→ 说明注释 → setlocal → 检查 node → 执行 → 失败暂停
 *
 * 为什么第一件事就是 chcp：Node 的日志是 UTF-8，路径也可能含中文。
 * 中文版 Windows 的控制台默认 GBK(936)，不切码页的话两者都会显示成乱码。
 *
 * @param {object} o
 * @param {string} o.title       脚本用途（英文，会出现在 rem 里）
 * @param {string} o.appName     应用名（可含中文；内部会转成 ASCII 标签）
 * @param {string} o.asciiFallback 名字非 ASCII 时用的替代标签（通常是 profile 名）
 * @param {string} o.invocation  要执行的东西，例如 `node "..\..\injector\noglass.js"`
 * @param {string[]} o.defaultArgs 默认参数
 * @param {string[]} o.notes     rem 注释行（英文）
 */
function renderCmd({ title, appName, asciiFallback, invocation, defaultArgs, notes = [], preset, fingerprint: fp }) {
  const label = asciiLabel(appName, asciiFallback);
  const argsLine = defaultArgs.join(' ');
  const lines = [
    '@echo off',
    'rem  Force UTF-8 in this console: Node writes its logs in UTF-8, and paths',
    'rem  may contain non-ASCII. Under the default GBK codepage both garble.',
    'chcp 65001 >nul 2>nul',
    'rem ===========================================================================',
    `rem  ${label} no-glass launcher -- ${title}`,
    'rem',
    `rem  Generated by no-glass-ele. Do not edit by hand:`,
    'rem  re-run "node gen.js build" after changing the profile.',
    `rem  profile-fingerprint: ${fp || '(none)'}`,
    'rem',
    'rem  Usage:',
    `rem    <this file>              ${preset ? `preset: ${preset}` : 'default preset'}`,
    'rem    <this file> --port 9500  extra args are passed through',
    'rem',
  ];

  // 名字含非 ASCII 时说明一句：这个文件用 ASCII 标签，全名在 README 里
  if (hasNonAscii(appName)) {
    lines.push('rem  (this launcher uses an ASCII label; the full display name is in README.md)');
    lines.push('rem');
  }

  lines.push(
    ...notes.map((n) => `rem  ${n}`),
    'rem',
    'rem  NOTE: This file is intentionally pure ASCII. A .cmd containing UTF-8',
    'rem        Chinese is mis-decoded under the default GBK console codepage,',
    'rem        which shreds the rem lines into bogus commands. See README.md.',
    'rem ===========================================================================',
    'setlocal',
    '',
    'where node >nul 2>nul',
    'if errorlevel 1 (',
    '  echo [noglass] Node.js not found. Please install Node 18+ first.',
    '  pause',
    '  exit /b 1',
    ')',
    '',
  );

  // 带默认参数 + 透传：有额外参数时，默认参数在前，用户参数在后（后者覆盖前者）
  lines.push(`if "%~1"=="" (`);
  lines.push(`  ${invocation} ${argsLine}`);
  lines.push(`) else (`);
  lines.push(`  ${invocation} ${argsLine} %*`);
  lines.push(`)`);
  lines.push('');
  lines.push('rem Keep the window open on failure so the error stays readable.');
  lines.push('if errorlevel 1 pause');
  lines.push('endlocal');

  const text = lines.join('\n');
  assertAscii(text, `${label}/${title}.cmd`);
  return toCrlf(text);
}

/**
 * 决定为某个应用生成哪些预设脚本。
 *
 * 规则（都有依据，不是拍脑袋）：
 *   · start.cmd          总是生成 —— 日常用法
 *   · start-debug.cmd    总是生成 —— 只列页面，排查用
 *   · start-isolated.cmd 仅当能隔离时生成。隔离要求应用没把 userData 写死，
 *                        或 profile 提供了 isolateEnv 私有开关。
 *   · start-native.cmd   仅当 fuse 允许 --inspect 时生成。加固过的应用上
 *                        这个脚本必然失败，生成出来只会误导。
 */
function planPresets(profile) {
  const d = profile.detected || {};
  const fuses = (d.fuses && d.fuses.table) || null;
  const runtime = profile.runtime || d.runtime || 'electron';
  const isTauri = runtime === 'tauri';
  const inspectOk = !isTauri && (!fuses || fuses.EnableNodeCliInspectArguments === 'on');
  // Tauri 没有 userData 覆盖这个概念（那是 Electron 的 API），
  // 但它的隔离走 WEBVIEW2_USER_DATA_FOLDER，同样能隔离
  const canIsolate = isTauri
    || profile.isolateEnv != null || d.userDataOverride === false || d.userDataOverride == null;

  const presets = [
    {
      file: 'start.cmd',
      title: 'daily use: launch + keep injecting',
      preset: '--launch --watch',
      args: ['--launch', '--watch'],
      notes: ['Starts the app with a debug port and keeps injecting the no-glass styles.'],
    },
    {
      file: 'start-debug.cmd',
      title: 'inspect: list injectable pages only',
      preset: '--launch --list',
      args: ['--launch', '--list'],
      notes: ['Launches the app, prints the injectable pages, then exits.'],
    },
  ];

  if (canIsolate) {
    presets.push({
      file: 'start-isolated.cmd',
      title: 'isolated instance: does not disturb the running app',
      preset: '--isolate --watch',
      args: ['--isolate', '--watch'],
      notes: [
        'Runs a separate instance with its own data directory.',
        canIsolate && profile.isolateEnv
          ? 'Uses this app\'s own switch to make --user-data-dir take effect.'
          : 'Uses --user-data-dir directly.',
      ],
    });
  }

  if (inspectOk) {
    presets.push({
      file: 'start-native.cmd',
      title: 'native: also remove window-level acrylic',
      preset: '--native --launch --watch',
      args: ['--native', '--launch', '--watch'],
      notes: [
        'Also removes the OS-level window blur (Windows acrylic / macOS vibrancy)',
        'and repaints the system title bar overlay with a solid color.',
        'Requires the main-process inspector, which some apps disable by fuse.',
      ],
    });
  }

  return presets;
}

/**
 * 生成 bundle 版的单文件脚本：把配置内联进去，整个目录可单独拷走。
 * 做法：读内核源码，在开头插入一段内联配置，并让 resolveConfig 优先使用它。
 */
function renderBundle(injectorSource, profile, cssText) {
  const banner = [
    '#!/usr/bin/env node',
    '/*',
    ' * BUNDLED build -- generated by no-glass-ele.',
    ` * App: ${profile.displayName || profile.name}`,
    ' * This file is self-contained: profile and stylesheet are inlined below.',
    ' * Regenerate with: node gen.js build <name> --bundle',
    ' */',
    '',
  ].join('\n');

  const inline = [
    '// ── inlined configuration (generated) ──────────────────────────────',
    `const __INLINE_PROFILE__ = ${JSON.stringify(profile, null, 2)};`,
    `const __INLINE_CSS__ = ${JSON.stringify(cssText)};`,
    '// ───────────────────────────────────────────────────────────────────',
    '',
  ].join('\n');

  // 去掉原文件开头的 shebang（我们自己加了）
  let src = injectorSource.replace(/^#!.*\r?\n/, '');

  // 让 resolveConfig 优先采用内联配置
  src = src.replace(
    'function loadProfile(p) {',
    `function loadProfile(p) {
  if (typeof __INLINE_PROFILE__ !== 'undefined' && __INLINE_PROFILE__) {
    return { __path: '(bundled)', __dir: __dirname, ...__INLINE_PROFILE__ };
  }`
  );

  // 样式表兜底：内联 CSS 直接可用
  src = src.replace(
    `  if (!fs.existsSync(cfg.css)) {
    const alt = path.join(HERE, 'no-glass.css');
    if (fs.existsSync(alt)) cfg.css = alt;
  }`,
    `  if (typeof __INLINE_CSS__ !== 'undefined' && __INLINE_CSS__ && !fs.existsSync(cfg.css)) {
    cfg.css = '(inlined)';
  } else if (!fs.existsSync(cfg.css)) {
    const alt = path.join(HERE, 'no-glass.css');
    if (fs.existsSync(alt)) cfg.css = alt;
  }`
  );

  src = src.replace(
    `  if (!fs.existsSync(cfg.css)) throw new Error(\`样式表不存在: \${cfg.css}\`);
  cfg.cssText = fs.readFileSync(cfg.css, 'utf8');`,
    `  if (cfg.css === '(inlined)') {
    cfg.cssText = __INLINE_CSS__;
  } else {
    if (!fs.existsSync(cfg.css)) throw new Error(\`样式表不存在: \${cfg.css}\`);
    cfg.cssText = fs.readFileSync(cfg.css, 'utf8');
  }`
  );

  return banner + inline + src;
}

