/** 把 fuse 表渲染成 markdown 表格。 */
function fuseTable(fuses) {
  if (!fuses || !fuses.table) return '_未探测到 fuse 表（可能不是 Electron 应用，或使用了裁剪构建）。_\n';
  const rows = Object.entries(fuses.table).map(([k, v]) => {
    const label = v === 'on' ? '开' : v === 'off' ? '关' : v === 'removed' ? '已移除' : v;
    return `| \`${k}\` | ${label} |`;
  });
  return ['| fuse | 状态 |', '|---|---|', ...rows].join('\n') + '\n';
}

function yesNo(v) {
  if (v === true) return '是';
  if (v === false) return '否';
  return '未知（需人工确认）';
}

